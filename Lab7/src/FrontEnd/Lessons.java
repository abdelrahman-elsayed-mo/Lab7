    private void loadlessons() {
         String courseId = courseIdField.getText().trim();
        if (courseId.isEmpty()) return;

        List<Lesson> lessons = courseService.getCourseLessons(courseId);

        Object[][] data = new Object[lessons.size()][2];
        for (int i = 0; i < lessons.size(); i++) {
            data[i][0] = lessons.get(i).getLessonId();
            data[i][1] = lessons.get(i).getTitle();
        }

        DefaultTableModel model = new DefaultTableModel(data, new String[]{"Lesson ID", "Title"}) {
            public boolean isCellEditable(int row, int column) { return false; }
        };
        lessonTable.setModel(model);
    }

   
