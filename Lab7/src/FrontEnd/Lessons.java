 private void addListeners() {
        // Load lessons when button clicked
        Load.addActionListener(e -> loadlessons());

        // Back button
        Back.addActionListener(e -> {
            CardLayout cl = (CardLayout) parentDashboard.getContentPanel().getLayout();
            cl.show(parentDashboard.getContentPanel(), "available");
        });

        // Open lesson content when table row clicked
        jTable1.addMouseListener(new MouseAdapter() {
            public void mouseClicked(MouseEvent evt) {
                int row = jTable1.getSelectedRow();
                if (row >= 0) {
                    String lessonId = jTable1.getValueAt(row, 0).toString();
                    parentDashboard.getLessonContentPanel();
                }
            }
        });
}

    

